from __future__ import annotations

DEFAULT_FG = (216, 222, 233)
DEFAULT_BG = (30, 30, 30)
DEFAULT_FG_INDEX = 256
DEFAULT_BG_INDEX = 257
SELECTION = "#3b4252"
